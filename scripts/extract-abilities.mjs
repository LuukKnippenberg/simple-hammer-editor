// Reads the game's Python ability registry (wars_game) and writes src/lw/gameAbilities.ts: every class
// with its own `name = '...'`, sorted into buildings, units, research and other abilities, with the English
// display name from resource/lambdawars_english.txt. Run: node scripts/extract-abilities.mjs [game dir]
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const game = process.argv[2] ?? 'C:/Program Files (x86)/Steam/steamapps/common/lambdawars-game/lambdawars';
const root = join(game, 'python', 'wars_game');

const files = [];
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { if (f !== '__pycache__' && f !== 'singleplayer') walk(p); }
    else if (f.endsWith('.py')) files.push(p);
  }
};
walk(root);

// English strings: UTF-16 LE "key" "value" pairs.
const loc = new Map();
const raw = readFileSync(join(game, 'resource', 'lambdawars_english.txt'));
const text = raw[0] === 0xff && raw[1] === 0xfe ? raw.toString('utf16le') : raw.toString('utf8');
for (const m of text.matchAll(/^\s*"([^"]+)"\s+"([^"]*)"/gm)) loc.set(m[1].toLowerCase(), m[2]);

/** class name -> { bases, name, displayname, cls } */
const classes = new Map();
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  const blocks = src.split(/^(?=class\s)/m).slice(1);
  for (const b of blocks) {
    const head = /^class\s+(\w+)\s*\(([^)]*)\)/.exec(b);
    if (!head) continue;
    const body = b.split(/\n(?=\S)/)[0];
    const key = (k) => new RegExp(`^ {4}${k}\\s*=\\s*['"]([^'"]+)['"]`, 'm').exec(body)?.[1];
    classes.set(head[1], { file: relative(root, f).replace(/\\/g, '/'), bases: head[2].split(',').map((s) => s.trim().split('.').pop()), name: key('name'), displayname: key('displayname'), cls: key('cls_name') });
  }
}
const isA = (c, re, seen = new Set()) => {
  if (!c || seen.has(c)) return false;
  seen.add(c);
  return classes.get(c)?.bases.some((b) => re.test(b) || isA(b, re, seen)) ?? false;
};
const faction = (file, name) => {
  const s = `${file} ${name}`;
  if (/combine|_comb_|^comb|metropolice|scanner|stalker|strider|hunter|manhack|dropship|gunship|synth|rollermine/.test(s)) return 'combine';
  if (/rebel|_reb_|citizen|vortigaunt|alyx|barney|dog|jeep/.test(s)) return 'rebels';
  if (/zombi|crab/.test(s)) return 'zombies';
  if (/antlion|mutalisk/.test(s)) return 'antlions';
  return 'other';
};

const out = new Map();
for (const [cn, c] of classes) {
  if (!c.name || out.has(c.name)) continue;
  const kind = c.name.startsWith('build_') || isA(cn, /BuildingInfo$/) ? 'building'
    : isA(cn, /^(AbilityUpgrade|AbilityUpgradeValue|AbilityUpgradePopCap)$/) || /^(AbilityUpgrade|AbilityUpgradeValue|AbilityUpgradePopCap)$/.test(c.bases[0]) ? 'research'
      : c.name.startsWith('unit_') || isA(cn, /^UnitInfo$/) ? 'unit' : 'ability';
  let dn = c.displayname;
  for (let p = classes.get(cn), n = 0; p && !dn && n < 10; p = classes.get(p.bases[0]), n++) dn = p.displayname;
  const label = dn?.startsWith('#') ? loc.get(dn.slice(1).toLowerCase()) ?? '' : dn ?? '';
  out.set(c.name, { name: c.name, kind, faction: faction(c.file, c.name), label, cls: c.cls ?? '', file: c.file });
}
const list = [...out.values()].sort((a, b) => a.kind.localeCompare(b.kind) || a.faction.localeCompare(b.faction) || a.name.localeCompare(b.name));
const ts = `// Generated by scripts/extract-abilities.mjs from the game's python/wars_game. Do not edit by hand.

export type GameAbilityKind = 'building' | 'unit' | 'research' | 'ability';

export interface GameAbility {
  /** The ability / unit info name: what wars_ability_manager, filter_unittype and AbilityCompleted use. */
  name: string;
  kind: GameAbilityKind;
  faction: string;
  /** English display name, when the game has one. */
  label: string;
  /** The entity class it spawns, when it differs from the name (buildings and units). */
  cls: string;
}

export const GAME_ABILITIES: GameAbility[] = [
${list.map((a) => `  { name: ${JSON.stringify(a.name)}, kind: '${a.kind}', faction: '${a.faction}', label: ${JSON.stringify(a.label)}, cls: ${JSON.stringify(a.cls)} },`).join('\n')}
];
`;
writeFileSync(new URL('../src/lw/gameAbilities.ts', import.meta.url), ts);
console.log(`${list.length} abilities: ${['building', 'unit', 'research', 'ability'].map((k) => `${list.filter((a) => a.kind === k).length} ${k}`).join(', ')}`);
